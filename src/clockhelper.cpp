// Active font pointer — set at the top of overdrawClock()
static const Glyph* gActiveFont = kFontPolymorph;

// ─────────────────────────────────────────────────────────────────────────────
// Font helpers
// ─────────────────────────────────────────────────────────────────────────────

static int glyphIndex(char c) {
    if (c >= '0' && c <= '9') return c - '0';
    if (c == ':') return 10;
    if (c == '.') return 11;
    if (c == 'A') return 12;
    if (c == 'M') return 13;
    if (c == 'P') return 14;
    return 15; // space / fallback
}

static int glyphWidth(char c) {
    return gActiveFont[glyphIndex(c)].w + 1; // +1 inter-character gap
}

static int strPixelWidth(const char* s) {
    int w = 0;
    while (*s) { w += glyphWidth(*s++); }
    return w > 0 ? w - 1 : 0; // no trailing gap
}

static void drawGlyph(char c, int x, int y, uint16_t color) {
    const Glyph& g = gActiveFont[glyphIndex(c)];
    for (int row = 0; row < 7; row++) {
        const uint8_t bits = g.rows[row];
        for (int col = 0; col < (int)g.w; col++) {
            if ((bits >> (g.w - 1 - col)) & 1) {
                matrix->drawPixel(x + col, y + row, color);
            }
        }
    }
}

static void drawStr(const char* s, int x, int y, uint16_t color) {
    while (*s) {
        drawGlyph(*s, x, y, color);
        x += glyphWidth(*s);
        s++;
    }
}

// ─────────────────────────────────────────────────────────────────────────────
// Gregorian calendar decomposition
// ─────────────────────────────────────────────────────────────────────────────

struct ClockTime { int hour, minute, second, day, month, year; };

static const uint8_t kDim[2][12] = {
    {31,28,31,30,31,30,31,31,30,31,30,31},
    {31,29,31,30,31,30,31,31,30,31,30,31},
};

static bool isLeap(int y) {
    return (y % 4 == 0 && y % 100 != 0) || (y % 400 == 0);
}

static ClockTime epochToTime(uint32_t epochSec, int16_t tzOffsetMin) {
    int32_t t = (int32_t)epochSec + (int32_t)tzOffsetMin * 60;
    if (t < 0) t = 0;

    ClockTime ct;
    ct.second = t % 60; t /= 60;
    ct.minute = t % 60; t /= 60;
    ct.hour   = t % 24; t /= 24;

    uint32_t days = (uint32_t)t;
    int y = 1970;
    while (true) {
        uint32_t diy = isLeap(y) ? 366 : 365;
        if (days < diy) break;
        days -= diy;
        y++;
    }
    ct.year = y;
    int leap = isLeap(y) ? 1 : 0;
    int m = 1;
    while (m <= 12 && days >= kDim[leap][m-1]) {
        days -= kDim[leap][m-1];
        m++;
    }
    ct.month = m;
    ct.day   = (int)days + 1;
    return ct;
}

// ─────────────────────────────────────────────────────────────────────────────
// overdrawClock — v1.6 (fontId now honoured)
// ─────────────────────────────────────────────────────────────────────────────

void overdrawClock(
    uint32_t epochSec,
    uint32_t wallMs,
    int16_t  tzOffsetMin,
    uint8_t  flags,
    uint8_t  fontId,        // ← was /*fontId*/ in v1.5 — now active
    int8_t   offX,
    int8_t   offY,
    uint16_t hoursCol,
    uint16_t minutesCol,
    uint16_t secondsCol,
    uint16_t colonCol,
    uint16_t dateCol,
    uint16_t ampmCol)
{
    if (!(flags & CLK_FLAG_PRESENT)) return;

    // Select font — clamp to valid range
    gActiveFont = kFonts[fontId < 7 ? fontId : 0];

    const bool h12      = flags & CLK_FLAG_H12;
    const bool showSec  = flags & CLK_FLAG_SECONDS;
    const bool showDate = flags & CLK_FLAG_DATE;
    const bool blinkCol = flags & CLK_FLAG_BLINK;
    const bool showAmPm = flags & CLK_FLAG_AMPM;

    // Derive current wall time
    const uint32_t wallSec = epochSec + wallMs / 1000;
    ClockTime ct = epochToTime(wallSec, tzOffsetMin);

    // Blink colon: off for the second half of each second
    const bool colonVisible = !blinkCol || (wallMs % 1000) < 500;

    // Build display strings
    char hBuf[4], mBuf[4], sBuf[4], ampmBuf[4], dateBuf[10];

    int dispHour = ct.hour;
    if (h12) {
        dispHour = ct.hour % 12;
        if (dispHour == 0) dispHour = 12;
        snprintf(hBuf,    sizeof(hBuf),    "%d",  dispHour);
        snprintf(ampmBuf, sizeof(ampmBuf), "%s",  ct.hour < 12 ? "AM" : "PM");
    } else {
        snprintf(hBuf,    sizeof(hBuf),    "%02d", dispHour);
        ampmBuf[0] = '\0';
    }
    snprintf(mBuf,    sizeof(mBuf),    "%02d", ct.minute);
    snprintf(sBuf,    sizeof(sBuf),    "%02d", ct.second);
    snprintf(dateBuf, sizeof(dateBuf), "%02d.%02d.%02d",
             ct.day, ct.month, ct.year % 100);

    // Measure time row width (mirrors ClockWidget spacing constants)
    int timeW = strPixelWidth(hBuf)
              + 2 + glyphWidth(':')   // spacingBeforeColon = 2
              + strPixelWidth(mBuf);
    if (showSec)  timeW += 2 + glyphWidth(':') + strPixelWidth(sBuf);
    if (showAmPm) timeW += 1 + strPixelWidth(ampmBuf);

    // Vertical layout
    const int charH  = 7;
    const int totalH = charH + (showDate ? charH + 2 : 0);
    const int startY = (REAL_HEIGHT - totalH) / 2 + (int)offY;
    const int timeY  = startY;
    const int dateY  = startY + charH + 2;

    // Draw time row (centered + offset)
    int cx = (PANEL_WIDTH - timeW) / 2 + (int)offX;

    // Hours
    drawStr(hBuf, cx, timeY, hoursCol);
    cx += strPixelWidth(hBuf);

    // Colon H:M  (spacingBeforeColon=2, colonVisualOffset=-1)
    cx += 2;
    if (colonVisible) drawGlyph(':', cx - 1, timeY, colonCol);
    cx += glyphWidth(':') - 1;

    // Minutes
    drawStr(mBuf, cx, timeY, minutesCol);
    cx += strPixelWidth(mBuf);

    // Colon M:S + seconds
    if (showSec) {
        cx += 2;
        if (colonVisible) drawGlyph(':', cx - 1, timeY, colonCol);
        cx += glyphWidth(':') - 1;
        drawStr(sBuf, cx, timeY, secondsCol);
        cx += strPixelWidth(sBuf);
    }

    // AM/PM
    if (showAmPm && ampmBuf[0]) {
        cx += 1;
        drawStr(ampmBuf, cx, timeY, ampmCol);
    }

    // Date row (centered below time)
    if (showDate) {
        const int dw = strPixelWidth(dateBuf);
        const int dx = (PANEL_WIDTH - dw) / 2 + (int)offX;
        drawStr(dateBuf, dx, dateY, dateCol);
    }

    // NOTE: flipDMABuffer() is called by displayTask after this returns.
}