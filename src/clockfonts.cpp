// ─────────────────────────────────────────────────────────────────────────────
// Multi-font clock renderer — v1.6
//
// Replaces the single kGlyphs[] table with one table per font.
// overdrawClock() now accepts fontId and selects the correct table.
//
// Glyph format (matches Dart font_organizer.dart exactly):
//   w        — pixel width (meaningful bits per row)
//   rows[7]  — row bitmasks, rows[0]=top, MSB=leftmost pixel
//
// Characters needed per font: '0'-'9', ':', '.', 'A', 'M', 'P', ' '
// Index mapping (same for every font):
//   0-9  → '0'-'9'
//   10   → ':'
//   11   → '.'
//   12   → 'A'
//   13   → 'M'
//   14   → 'P'
//   15   → ' ' (space / fallback)
//
// NOTE: Waterfox '0' and '8' are 6 px wide, 'M' is 9 px wide — these fit
// in uint8_t if we shift the top bit right by 1 (losing nothing, since those
// glyphs only use bits 0-5 of each byte). The Dart-side bitmasks are stored
// MSB-first in a wider int, so we just take the low N bits.
// ─────────────────────────────────────────────────────────────────────────────

struct Glyph { uint8_t w; uint8_t rows[7]; };

// Helper: select glyph index from character
static int glyphIndex(char c) {
    if (c >= '0' && c <= '9') return c - '0';
    if (c == ':') return 10;
    if (c == '.') return 11;
    if (c == 'A') return 12;
    if (c == 'M') return 13;
    if (c == 'P') return 14;
    return 15; // space / fallback
}

