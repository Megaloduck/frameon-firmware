const Glyph* gActiveFont     = kFontPolymorph;
const Glyph* gActiveAlphabet = kFontPolymorphAlphabet;

void fontSetActive(uint8_t fontId) {
    const uint8_t fid = fontId < 7 ? fontId : 0;
    gActiveFont     = kFonts[fid];
    gActiveAlphabet = kFontAlphabets[fid];
}


// ═════════════════════════════════════════════════════════════════════════════
// DIGIT / PUNCTUATION HELPERS
// ═════════════════════════════════════════════════════════════════════════════

int glyphIndex(char c) {
    if (c >= '0' && c <= '9') return c - '0';
    if (c == ':') return 10;
    if (c == '.') return 11;
    if (c == 'A') return 12;
    if (c == 'M') return 13;
    if (c == 'P') return 14;
    return 15; // space / fallback
}

int glyphWidth(char c) {
    return gActiveFont[glyphIndex(c)].w + 1; // +1 inter-character gap
}

int textWidth(const char* s) {
    int w = 0;
    while (*s) { w += glyphWidth(*s++); }
    return w > 0 ? w - 1 : 0; // strip trailing gap
}

void drawGlyph(char c, int x, int y, uint16_t color) {
    const Glyph& g = gActiveFont[glyphIndex(c)];
    for (int row = 0; row < 7; row++) {
        const uint16_t bits = g.rows[row];
        for (int col = 0; col < (int)g.w; col++) {
            if ((bits >> (g.w - 1 - col)) & 1) {
                matrix->drawPixel(x + col, y + row, color);
            }
        }
    }
}

void drawText(const char* s, int x, int y, uint16_t color) {
    while (*s) {
        drawGlyph(*s, x, y, color);
        x += glyphWidth(*s++);
    }
}


// ═════════════════════════════════════════════════════════════════════════════
// LETTER / LABEL HELPERS
// ═════════════════════════════════════════════════════════════════════════════

const Glyph* letterGlyph(char c) {
    if (c >= 'A' && c <= 'Z') return &gActiveAlphabet[c - 'A'];
    if (c >= 'a' && c <= 'z') return &gActiveAlphabet[c - 'a'];
    return nullptr;
}

int letterWidth(char c) {
    const Glyph* g = letterGlyph(c);
    return g ? (g->w + 1) : 0;
}

int labelWidth(const char* s) {
    int w = 0;
    while (*s) { w += letterWidth(*s++); }
    return w > 0 ? w - 1 : 0;
}

void drawLetter(char c, int x, int y, uint16_t color) {
    const Glyph* g = letterGlyph(c);
    if (!g) return;
    for (int row = 0; row < 7; row++) {
        const uint16_t bits = g->rows[row];
        for (int col = 0; col < (int)g->w; col++) {
            if ((bits >> (g->w - 1 - col)) & 1) {
                matrix->drawPixel(x + col, y + row, color);
            }
        }
    }
}

void drawLabel(const char* s, int x, int y, uint16_t color) {
    while (*s) {
        if ((*s >= 'A' && *s <= 'Z') || (*s >= 'a' && *s <= 'z')) {
            drawLetter(*s, x, y, color);
            x += letterWidth(*s);
        }
        s++;
    }
}